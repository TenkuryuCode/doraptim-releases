#!/bin/sh
# Write the package-manager files for a published release, laid out as they are kept in the
# public downloads repository, which is also the Homebrew tap and the Scoop bucket:
#   Formula/doraptim.rb                                  (macOS and Linux, Homebrew)
#   bucket/doraptim.json                                 (Windows, Scoop)
#   winget/manifests/t/TenkuryuCode/DoRaptim/<version>/  (Windows, winget; submitted to Microsoft)
#
# The canonical copy is in the private repository, with its tests in scripts/tests.sh; the
# downloads repository runs a copy of it when a release is published.
#
# usage: scripts/package-manifests.sh <version> <SHA256SUMS> <output directory> [release notes file]
#
# The checksums come from the release's SHA256SUMS, so run this only after the release is
# published: the files point at its public download URLs.
set -eu

if [ $# -lt 3 ] || [ $# -gt 4 ]; then
    echo "usage: $0 <version> <SHA256SUMS> <output directory> [release notes file]" >&2
    exit 2
fi
version=$1
sums=$2
out=$3

if ! printf '%s\n' "$version" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$'; then
    echo "version \"$version\" is not a semantic version" >&2
    exit 2
fi
[ -f "$sums" ] || { echo "cannot read $sums" >&2; exit 2; }

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
notes=
if [ "$#" -eq 4 ]; then
    [ -f "$4" ] || { echo "cannot read release notes file" >&2; exit 2; }
    notes=$(cat "$4")
elif [ -f "$script_dir/release-notes.sh" ] && [ -f "$script_dir/../CHANGELOG.md" ]; then
    notes=$(sh "$script_dir/release-notes.sh" "$version")
fi
notes_json=
if [ -n "$notes" ]; then
    notes_json=$(printf '%s' "$notes" | node -e '
const fs = require("fs");
const lines = fs.readFileSync(0, "utf8").split(/\r?\n/).map(line => line.trim());
const bullets = lines.filter(line => /^[-*] /.test(line)).map(line => line.slice(2));
const paragraphs = lines.filter(line => line && !line.startsWith("#"));
const summary = (bullets.length ? bullets : paragraphs).slice(0, 3).join(" ");
process.stdout.write(JSON.stringify(Array.from(summary).slice(0, 1000).join("")));
')
fi

repository=${DORAPTIM_RELEASE_REPOSITORY:-TenkuryuCode/doraptim-releases}
releases="https://github.com/$repository"
website=${DORAPTIM_WEBSITE_URL:-https://doraptim.com}
website=${website%/}
base="$releases/releases/download/v$version"
homepage="$website"

# The SHA-256 of one release file, or fail if SHA256SUMS does not list it.
sha() {
    hash=$(awk -v file="$1" '{ name = $2; sub(/^\*/, "", name); if (name == file) print $1 }' "$sums")
    if ! printf '%s\n' "$hash" | grep -Eq '^[0-9a-f]{64}$'; then
        echo "SHA256SUMS has no valid entry for $1" >&2
        exit 1
    fi
    printf '%s' "$hash"
}

mac_arm="doraptim-$version-aarch64-apple-darwin.tar.gz"
mac_intel="doraptim-$version-x86_64-apple-darwin.tar.gz"
linux="doraptim-$version-x86_64-unknown-linux-gnu.tar.gz"
windows_dir="doraptim-$version-x86_64-pc-windows-msvc"
windows_zip="$windows_dir.zip"
windows_setup="doraptim-$version-windows-x86_64-setup.exe"

mac_arm_sha=$(sha "$mac_arm")
mac_intel_sha=$(sha "$mac_intel")
linux_sha=$(sha "$linux")
windows_zip_sha=$(sha "$windows_zip")
# winget expects upper case. Not piped, so a missing entry still stops the script.
windows_setup_sha=$(sha "$windows_setup")
windows_setup_sha=$(printf '%s' "$windows_setup_sha" | tr 'a-f' 'A-F')

# -- Homebrew ----------------------------------------------------------------------------------
mkdir -p "$out/Formula"
cat > "$out/Formula/doraptim.rb" <<RUBY
# Generated by scripts/package-manifests.sh for DoRaptim $version. Do not edit by hand.
class Doraptim < Formula
  desc "Download manager engine for the DoRaptim browser extension"
  homepage "$homepage"
  version "$version"
  license :cannot_represent

  on_macos do
    on_arm do
      url "$base/$mac_arm"
      sha256 "$mac_arm_sha"
    end
    on_intel do
      url "$base/$mac_intel"
      sha256 "$mac_intel_sha"
    end
  end

  on_linux do
    on_intel do
      url "$base/$linux"
      sha256 "$linux_sha"
    end
  end

  def install
    bin.install "doraptim"
    doc.install "README.md", "LICENSE", "LICENSE-MIT", "NOTICE", "TERMS-OF-USE.md", "TERMS-OF-USE.id.md"
  end

  def caveats
    <<~EOS
      Connect the engine to the DoRaptim browser extension:
        doraptim setup

      Before uninstalling, remove that connection and the engine's queue:
        doraptim uninstall --yes
        brew uninstall doraptim

      Use of DoRaptim is subject to its terms of use:
        #{doc}/TERMS-OF-USE.md
    EOS
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/doraptim version").strip
  end
end
RUBY

# -- Scoop -------------------------------------------------------------------------------------
mkdir -p "$out/bucket"
cat > "$out/bucket/doraptim.json" <<JSON
{
    "version": "$version",
    "description": "Download manager engine for the DoRaptim browser extension",
    "homepage": "$homepage",
    "license": {
        "identifier": "Proprietary",
        "url": "https://raw.githubusercontent.com/$repository/main/TERMS-OF-USE.md"
    },
    "architecture": {
        "64bit": {
            "url": "$base/$windows_zip",
            "hash": "$windows_zip_sha",
            "extract_dir": "$windows_dir"
        }
    },
    "bin": "doraptim.exe",
    "post_install": [
        "& \"\$dir\\\\doraptim.exe\" setup"
    ],
    "pre_uninstall": [
        "& \"\$dir\\\\doraptim.exe\" stop",
        "& \"\$dir\\\\doraptim.exe\" host uninstall"
    ],
    "notes": [
        "The engine is connected to the DoRaptim browser extension.",
        "Use of DoRaptim is subject to its terms of use (TERMS-OF-USE.md in the install folder)."
    ]
}
JSON

# -- winget ------------------------------------------------------------------------------------
winget="$out/winget/manifests/t/TenkuryuCode/DoRaptim/$version"
mkdir -p "$winget"
cat > "$winget/TenkuryuCode.DoRaptim.yaml" <<YAML
# Generated by scripts/package-manifests.sh for DoRaptim $version.
PackageIdentifier: TenkuryuCode.DoRaptim
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
YAML
cat > "$winget/TenkuryuCode.DoRaptim.installer.yaml" <<YAML
# Generated by scripts/package-manifests.sh for DoRaptim $version.
PackageIdentifier: TenkuryuCode.DoRaptim
PackageVersion: $version
InstallerType: inno
Scope: user
InstallModes:
  - interactive
  - silent
  - silentWithProgress
InstallerSwitches:
  Silent: /VERYSILENT /SUPPRESSMSGBOXES /NORESTART /ACCEPTTERMS
  SilentWithProgress: /SILENT /SUPPRESSMSGBOXES /NORESTART /ACCEPTTERMS
UpgradeBehavior: install
ProductCode: '{A541FDF7-806D-4C72-AE94-D5C9C88C5708}_is1'
Commands:
  - doraptim
Installers:
  - Architecture: x64
    InstallerUrl: $base/$windows_setup
    InstallerSha256: $windows_setup_sha
ManifestType: installer
ManifestVersion: 1.6.0
YAML
cat > "$winget/TenkuryuCode.DoRaptim.locale.en-US.yaml" <<YAML
# Generated by scripts/package-manifests.sh for DoRaptim $version.
PackageIdentifier: TenkuryuCode.DoRaptim
PackageVersion: $version
PackageLocale: en-US
Publisher: Tenkuryu Code
PublisherUrl: $website
PublisherSupportUrl: $releases/issues
PrivacyUrl: $website/en/privacy/
Agreements:
  - AgreementLabel: Terms of Use
    AgreementUrl: $website/en/terms/
  - AgreementLabel: Privacy Policy
    AgreementUrl: $website/en/privacy/
PackageName: DoRaptim
PackageUrl: $website
License: Proprietary
LicenseUrl: $website/en/terms/
ShortDescription: Download manager engine for the DoRaptim browser extension.
Description: DoRaptim takes over browser downloads and runs them with parallel connections, resume, and a persistent queue. The installer connects the engine to the DoRaptim extension for Chrome.
Tags:
  - download-manager
  - downloader
ReleaseNotesUrl: $releases/releases/tag/v$version
ManifestType: defaultLocale
ManifestVersion: 1.6.0
YAML

# A signed latest.json is what `doraptim update` reads. The signature is written when
# DORAPTIM_UPDATE_SIGNING_KEY (32-byte hex Ed25519 seed) is set; otherwise only the JSON.
channel=stable
case "$version" in
    *-beta*) channel=beta ;;
    *-rc*) channel=rc ;;
    *-*) channel=alpha ;;
esac
{
    printf '{\n'
    printf '  "version": "%s",\n' "$version"
    printf '  "channel": "%s",\n' "$channel"
    if [ -n "$notes_json" ]; then
        printf '  "notes": %s,\n' "$notes_json"
    fi
    printf '  "protocol": 2,\n'
    printf '  "min_extension": "%s",\n' "$version"
    printf '  "min_engine": "%s",\n' "$version"
    printf '  "assets": [\n'
    first=1
    for file in "$mac_arm" "$mac_intel" "$linux" "$windows_zip" "$windows_setup" \
        "doraptim-$version-macos-arm64.pkg" "doraptim-$version-macos-x86_64.pkg" \
        "doraptim-extension-$version-chrome.zip"; do
        hash=$(awk -v file="$file" '{ name = $2; sub(/^\*/, "", name); if (name == file) print $1 }' "$sums" || true)
        [ -n "$hash" ] || continue
        [ "$first" = 1 ] || printf ',\n'
        first=0
        printf '    {"name": "%s", "url": "%s/%s", "sha256": "%s"}' "$file" "$base" "$file" "$hash"
    done
    printf '\n  ]\n}\n'
} > "$out/latest.json"

if [ -n "${DORAPTIM_UPDATE_SIGNING_KEY-}" ]; then
    node -e '
const { createPrivateKey, sign } = require("crypto");
const fs = require("fs");
const seed = Buffer.from(process.env.DORAPTIM_UPDATE_SIGNING_KEY, "hex");
if (seed.length !== 32) { console.error("DORAPTIM_UPDATE_SIGNING_KEY must be 32 bytes hex"); process.exit(1); }
const pkcs8 = Buffer.concat([Buffer.from("302e020100300506032b657004220420", "hex"), seed]);
const key = createPrivateKey({ key: pkcs8, format: "der", type: "pkcs8" });
const body = fs.readFileSync(process.argv[1]);
fs.writeFileSync(process.argv[1] + ".sig", sign(null, body, key).toString("hex") + "\n");
' "$out/latest.json"
fi

echo "wrote Formula, bucket, winget, and latest.json in $out for $version"
